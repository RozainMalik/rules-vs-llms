"""
Implementation (c): LLM-COMPILED RULES — the COMPILE step (run once per Budget).

The LLM reads the rule text and writes a pure-Python module with
    def compute(inp: dict) -> dict
That module is saved to compiled/fy<year>.py, a human REVIEWS it (reading the
code + running the test suite), records the review in compiled/REVIEW.md, and
from then on calculator.py runs it with NO LLM at query time.

Run:  python -m project_a.impl_llm_compiled.compiler 2024-25 [--sample N]
"""

from __future__ import annotations

import ast
import hashlib
import sys
from datetime import date
from pathlib import Path

from common.llm import LLM

HERE = Path(__file__).resolve().parent
TEXT_DIR = HERE.parent / "rules_text"
OUT_DIR = HERE / "compiled"

SYSTEM = "You are a careful engineer who translates tax law into exact, auditable Python code."

PROMPT = """Translate the rule text below into ONE self-contained Python 3.10 module.

Requirements:
- Define `def compute(inp: dict) -> dict`. `inp` has these keys (amounts are annual rupees, ints;
  booleans as bool; all keys always present, 0/False if absent):
  gross_salary, age, hra_received, basic_plus_da, rent_paid, rent_city_is_metro,
  home_loan_interest, sec_80c, sec_80ccd_1b, health_ins_self, health_ins_parents, parents_senior
- Return {"old": R, "new": R} where R = {"total_income": int, "tax_payable": int,
  "trace": [{"kind": "income"|"tax", "description": str, "amount": str, "clause": str}, ...]}
  income-kind amounts must sum to total_income; tax-kind amounts must sum to tax_payable.
  Put amounts in the trace as str(Decimal) so nothing is lost.
- Use decimal.Decimal for ALL money arithmetic (never float). Construct Decimals from int or str.
- Put every rate, limit and threshold in a CONSTANTS section at the top, each with a comment
  naming its section, so a reviewer can check them against the law.
- Standard library only. No I/O, no imports other than decimal.
- Follow the order of computation implied by the text exactly, including Sec 288A and 288B
  rounding, the Sec 87A rebate and its marginal relief, surcharge marginal relief and cess.

Return ONLY the Python code, no explanation, no markdown fences.

RULE TEXT:
{rule_text}"""


def compile_rules(fiscal_year: str, sample: int = 0) -> Path:
    tag = fiscal_year.replace("-", "_")
    rule_text = (TEXT_DIR / f"fy{tag}.md").read_text()
    llm = LLM()
    resp = llm.generate(PROMPT.replace("{rule_text}", rule_text), system=SYSTEM, sample=sample)

    code = resp.text.strip()
    if code.startswith("```"):
        code = code.split("\n", 1)[1].rsplit("```", 1)[0]
    ast.parse(code)  # fail fast on syntax errors

    header = (
        f'"""\nAUTO-GENERATED by {llm.model} from rules_text/fy{tag}.md on {date.today()}.\n'
        f"rule-text sha256: {hashlib.sha256(rule_text.encode()).hexdigest()[:16]}\n"
        f"compile sample: {sample} | tokens in/out: {resp.input_tokens}/{resp.output_tokens} "
        f"| cost ${resp.cost_usd:.5f}\n"
        f'DO NOT EDIT BY HAND — review, then record the verdict in REVIEW.md.\n"""\n\n'
    )
    OUT_DIR.mkdir(exist_ok=True)
    out = OUT_DIR / f"fy{tag}.py"
    out.write_text(header + code + "\n")
    print(f"wrote {out}  ({len(code.splitlines())} lines, {resp.latency_s}s, ${resp.cost_usd:.5f})")
    return out


if __name__ == "__main__":
    fy = sys.argv[1] if len(sys.argv) > 1 else "2024-25"
    s = int(sys.argv[sys.argv.index("--sample") + 1]) if "--sample" in sys.argv else 0
    compile_rules(fy, s)
