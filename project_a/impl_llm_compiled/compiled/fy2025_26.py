def round_nearest_ten(amount: Decimal) -> Decimal:
    """Sec 288A/288B rounding: drop paise (floor to whole rupees), 
    then round to nearest multiple of 10 (5 or more rounds up)."""
    whole_rupees = amount.quantize(Decimal('1'), rounding=ROUND_FLOOR)
    remainder = whole_rupees % Decimal('10')
    if remainder >= Decimal('5'):
        return whole_rupees + (Decimal('10') - remainder)
    else:
        return whole_rupees - remainder


def compute_slabs(taxable_income: Decimal, slabs: list) -> tuple[Decimal, list[tuple[str, Decimal]]]:
    """Computes slab-wise tax and returns total slab tax and a list of (description, amount) per band."""
    total_tax = Decimal('0')
    band_details = []
    for lower, upper, rate in slabs:
        if taxable_income <= lower:
            break
        if upper is None or taxable_income < upper:
            taxable_in_band = taxable_income - lower
        else:
            taxable_in_band = upper - lower
        
        band_tax = taxable_in_band * rate
        total_tax += band_tax
        
        upper_str = f"up to {upper:n}" if upper else "above"
        desc = f"Tax at {rate * Decimal('100')}% on slab {lower:n} to {upper_str}"
        band_details.append((desc, band_tax))
        
    return total_tax, band_details


