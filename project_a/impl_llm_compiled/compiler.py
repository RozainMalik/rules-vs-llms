"""
Implementation (c): LLM-COMPILED RULES — the COMPILE step (run once per Budget).

The LLM reads the rule text and writes a pure-Python module with
    def compute(inp: dict) -> dict
A human REVIEWS the code and the test results; problems go into a feedback file
(review/fy<year>_roundN.txt) and we recompile. Because one compile is not
reliable, compile_and_select() generates several candidates and keeps the first
that passes the edge-case suite. From then on calculator.py runs the selected
module with NO LLM at query time.

Run:  python -m project_a.impl_llm_compiled.compiler 2024-25 [--feedback FILE] [--candidates N]

Review loop: if the reviewer finds problems, write them to a feedback file and
recompile with --feedback. Generated code is never edited by hand, so the
compiled module always corresponds to (rule text + prompt + feedback).
"""

from __future__ import annotations

import ast
import hashlib
import json
import sys
from datetime import date
from decimal import Decimal
from pathlib import Path

from common.llm import LLM

HERE = Path(__file__).resolve().parent
TEXT_DIR = HERE.parent / "rules_text"
OUT_DIR = HERE / "compiled"

SYSTEM = "You are a careful engineer who translates tax law into exact, auditable Python code."

PROMPT = """Translate the rule text below into ONE self-contained Python 3.10 module.

Requirements:
- Define `def compute(inp: dict) -> dict`. `inp` has these keys (amounts are annual rupees, ints;
  booleans as bool; all keys always present, 0/False if absent):
  gross_salary, age, hra_received, basic_plus_da, rent_paid, rent_city_is_metro,
  home_loan_interest, sec_80c, sec_80ccd_1b, health_ins_self, health_ins_parents, parents_senior
- Return {"old": R, "new": R} where R = {"total_income": int, "tax_payable": int,
  "trace": [{"kind": "income"|"tax", "description": str, "amount": str, "clause": str}, ...]}
  income-kind amounts must sum to total_income; tax-kind amounts must sum to tax_payable.
  Put amounts in the trace as str(Decimal) so nothing is lost.
- Use decimal.Decimal for ALL money arithmetic (never float). Construct Decimals from int or str.
- Put every rate, limit and threshold in a CONSTANTS section at the top, each with a comment
  naming its section, so a reviewer can check them against the law.
- Standard library only. No I/O, no imports other than decimal.
- Follow the order of computation implied by the text exactly, including Sec 288A and 288B
  rounding, the Sec 87A rebate and its marginal relief, surcharge marginal relief and cess.

Return ONLY the Python code, no explanation, no markdown fences.

RULE TEXT:
{rule_text}"""


def compile_rules(fiscal_year: str, sample: int = 0, feedback: str = "") -> tuple[str, dict]:
    """One LLM compile. Returns (module source incl. header, metadata)."""
    tag = fiscal_year.replace("-", "_")
    rule_text = (TEXT_DIR / f"fy{tag}.md").read_text()
    prompt = PROMPT.replace("{rule_text}", rule_text)
    if feedback:
        prompt += ("\n\nREVIEWER FEEDBACK on a previous version of this module. "
                   "Fix every point:\n" + feedback)
    llm = LLM()
    resp = llm.generate(prompt, system=SYSTEM, sample=sample)

    code = resp.text.strip()
    if code.startswith("```"):
        code = code.split("\n", 1)[1].rsplit("```", 1)[0]

    header = (
        f'"""\nAUTO-GENERATED by {llm.model} from rules_text/fy{tag}.md on {date.today()}.\n'
        f"rule-text sha256: {hashlib.sha256(rule_text.encode()).hexdigest()[:16]}\n"
        f"feedback: {'yes' if feedback else 'none'} | compile sample: {sample} | "
        f"tokens in/out: {resp.input_tokens}/{resp.output_tokens} | cost ${resp.cost_usd:.5f}\n"
        f'DO NOT EDIT BY HAND — fix via review feedback + recompile (see review/).\n"""\n\n'
    )
    meta = {"sample": sample, "latency_s": resp.latency_s, "cost_usd": round(resp.cost_usd, 5),
            "lines": len(code.splitlines())}
    return header + code + "\n", meta


def evaluate(source: str, cases: list[dict]) -> dict:
    """Run a candidate module (no LLM) on test cases.
    Returns counts of rupee-exact cases and of traces that do not add up."""
    try:
        ast.parse(source)
        namespace: dict = {}
        exec(compile(source, "<candidate>", "exec"), namespace)
        compute = namespace["compute"]
    except Exception as e:  # noqa: BLE001
        return {"correct": 0, "total": len(cases), "trace_errors": 0, "load_error": repr(e)[:200]}
    correct = trace_errors = crashes = 0
    for c in cases:
        try:
            out = compute(dict(c["input"]))
            ok = all(out[r]["tax_payable"] == c["expected"][r] for r in ("old", "new"))
            for r in ("old", "new"):
                tax_sum = sum(Decimal(str(t["amount"])) for t in out[r]["trace"] if t.get("kind") == "tax")
                if tax_sum != out[r]["tax_payable"]:
                    trace_errors += 1
                    break
        except Exception:  # noqa: BLE001
            ok, crashes = False, crashes + 1
        correct += ok
    return {"correct": correct, "total": len(cases), "trace_errors": trace_errors, "crashes": crashes}


def cases_for(fiscal_year: str) -> list[dict]:
    name = "cases.json" if fiscal_year == "2024-25" else f"cases_{fiscal_year.replace('-', '_')}.json"
    return json.loads((HERE.parent / "tests" / name).read_text())


def compile_and_select(fiscal_year: str, feedback: str = "", candidates: int = 5) -> dict:
    """GENERATE-AND-VERIFY. Compile up to N candidates; SELECT on edge cases only
    (non-random categories), REPORT on the full suite; stop at the first candidate
    that passes every edge case with a trace that adds up."""
    tag = fiscal_year.replace("-", "_")
    cases = cases_for(fiscal_year)
    edge = [c for c in cases if c["category"] != "random"]
    log, best = [], None
    for sample in range(candidates):
        source, meta = compile_rules(fiscal_year, sample, feedback)
        sel, full = evaluate(source, edge), evaluate(source, cases)
        entry = {**meta, "edge": sel, "full": full}
        log.append(entry)
        print(f"  candidate {sample}: edge {sel['correct']}/{sel['total']}, "
              f"full {full['correct']}/{full['total']}, trace errors {full['trace_errors']}")
        score = (sel["correct"], -sel["trace_errors"])
        if best is None or score > best[0]:
            best = (score, source, sample)
        if sel["correct"] == sel["total"] and sel["trace_errors"] == 0:
            break
    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / f"fy{tag}.py").write_text(best[1])
    summary = {"fiscal_year": fiscal_year, "feedback_used": bool(feedback), "selected_sample": best[2],
               "passed_all_edge_cases": best[0][0] == len(edge), "candidates": log}
    (HERE / "review" / f"fy{tag}_selection.json").write_text(json.dumps(summary, indent=1))
    print(f"selected candidate {best[2]} -> compiled/fy{tag}.py")
    return summary


if __name__ == "__main__":
    fy = sys.argv[1] if len(sys.argv) > 1 else "2024-25"
    fb = Path(sys.argv[sys.argv.index("--feedback") + 1]).read_text() if "--feedback" in sys.argv else ""
    n = int(sys.argv[sys.argv.index("--candidates") + 1]) if "--candidates" in sys.argv else 5
    compile_and_select(fy, fb, n)
