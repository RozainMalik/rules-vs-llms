def round_nearest_ten(amount: Decimal) -> Decimal:
    """Sec 288A / 288B rounding: floor paise, then round to nearest 10."""
    whole = amount.quantize(Decimal("1"), rounding=ROUND_FLOOR)
    remainder = whole % Decimal("10")
    if remainder >= Decimal("5"):
        return whole + (Decimal("10") - remainder)
    else:
        return whole - remainder


def compute_slab_tax(taxable_income: Decimal, slabs: list[tuple[Decimal, Decimal | None, Decimal]]) -> tuple[Decimal, list[tuple[str, Decimal]]]:
    total_tax = Decimal("0")
    breakdown = []
    for lower, upper, rate in slabs:
        if taxable_income <= lower:
            break
        if upper is None:
            taxable_amount = taxable_income - lower
            desc_upper = "above"
        else:
            taxable_amount = min(taxable_income, upper) - lower
            desc_upper = str(upper)
        if taxable_amount > 0:
            tax_for_slab = taxable_amount * rate
            total_tax += tax_for_slab
            breakdown.append((f"Tax at {rate*100}% on slab {lower} to {desc_upper}", tax_for_slab))
    return total_tax, breakdown


def get_surcharge_rate(total_income: Decimal, is_new: bool) -> Decimal:
    rates = SURCHARGE_RATES_NEW if is_new else SURCHARGE_RATES_OLD
